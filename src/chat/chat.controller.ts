import {
  Body,
  Controller,
  Delete,
  Get,
  Logger,
  Param,
  Post,
  Res,
} from '@nestjs/common';
import { type AuthUser, CurrentUser } from '../auth/current-user.decorator';
import {
  ResponseMessage,
  SkipEnvelope,
} from '../decorators/response-message.decorator';
import { ChatService } from './chat.service';
import { SendMessageDto } from './dto/send-message.dto';
import { type FastifyReply } from 'fastify/types/reply';
import { ChatEvent } from '../types/chat';
import { AppException } from '../exceptions/app.exception';
import { ErrorCode } from '../types/error-code';
import { ApiOperation } from '@nestjs/swagger';
import { ApiEnvelope } from '../swagger/api-envelope.decorator';
import { SendMessageResponseDto } from './dto/send-message-response.dto';
import { MessageResponseDto } from './dto/message-response.dto';
import { EmptyReponseDto } from '../swagger/dto/empty-response.dto';

@Controller('projects/:projectId')
export class ChatController {
  constructor(private readonly chat: ChatService) {}
  private readonly logger = new Logger(ChatController.name);

  /**
   * List all messages in a project, only if owned by the current user.
   * @param user - The current authenticated user, injected by the CurrentUser decorator.
   * @param projectId - The ID of the project to list messages from.
   * @returns An array of messages in the project.
   * @throws ProjectNotFoundException if the project does not exist or is not owned by the user.
   */
  @Get('messages')
  @ApiEnvelope(MessageResponseDto, { isArray: true })
  list(@CurrentUser() user: AuthUser, @Param('projectId') projectId: string) {
    return this.chat.list(user.id, projectId);
  }

  /**
   * Send a message in a project, only if owned by the current user. Use streaming endpoints for real-time responses.
   * @deprecated This endpoint is deprecated. Use the streaming endpoints for real-time responses.
   * @param user - The current authenticated user, injected by the CurrentUser decorator.
   * @param projectId - The ID of the project to send the message to.
   * @param dto - The message content to send.
   * @returns An object containing the user message and assistant message.
   * @throws ProjectNotFoundException if the project does not exist or is not owned by the user.
   */
  @Post('messages')
  @ApiOperation({
    summary: 'Send a message in a project (Deprecated)',
    deprecated: true,
  })
  send(
    @CurrentUser() user: AuthUser,
    @Param('projectId') projectId: string,
    @Body() dto: SendMessageDto,
  ) {
    return this.chat.send(user.id, projectId, dto.content);
  }

  /**
   * Summarise a project, only if owned by the current user.
   * @param user - The current authenticated user, injected by the CurrentUser decorator.
   * @param projectId - The ID of the project to summarise.
   * @returns A message containing the summary generated by the LLM.
   * @throws ConversationEmptyException if there are no messages to summarise.
   * @throws ProjectNotFoundException if the project does not exist or is not owned by the user.
   */
  @Post('summary')
  @ApiEnvelope(SendMessageResponseDto)
  summarise(
    @CurrentUser() user: AuthUser,
    @Param('projectId') projectId: string,
  ) {
    return this.chat.summarise(user.id, projectId);
  }

  /**
   * Reset a project, only if owned by the current user.
   * @param user - The current authenticated user, injected by the CurrentUser decorator.
   * @param projectId - The ID of the project to reset.
   * @returns A message indicating the conversation has been reset.
   * @throws ProjectNotFoundException if the project does not exist or is not owned by the user.
   */
  @Delete('messages')
  @ApiEnvelope(EmptyReponseDto)
  @ResponseMessage('Conversation reset')
  reset(@CurrentUser() user: AuthUser, @Param('projectId') projectId: string) {
    return this.chat.reset(user.id, projectId);
  }

  /**
   * Stream messages in a project, only if owned by the current user.
   * @param user - The current authenticated user, injected by the CurrentUser decorator.
   * @param projectId - The ID of the project to stream messages from.
   * @param dto - The message content to send.
   * @param reply - The Fastify reply object, used to send streaming responses.
   * @returns A stream of chat events, including tokens and final messages.
   * @throws ProjectNotFoundException if the project does not exist or is not owned by the user.
   * @throws LlmUnavailableException if the LLM service is unavailable.
   * @throws LlmResponseBlockedException if the LLM response is blocked due to content filtering.
   * @throws TooManyRequestsException if the user exceeds the rate limit for streaming requests.
   */
  @Post('messages/stream')
  @SkipEnvelope()
  async sendStream(
    @CurrentUser() user: AuthUser,
    @Param('projectId') projectId: string,
    @Body() dto: SendMessageDto,
    @Res() reply: FastifyReply,
  ) {
    const ac = this.abortOnDisconnect(reply);
    await this.pipe(
      reply,
      this.chat.streamReply(user.id, projectId, dto.content, ac.signal),
    );
  }

  /**
   * Stream summary in a project, only if owned by the current user.
   * @param user - The current authenticated user, injected by the CurrentUser decorator.
   * @param projectId - The ID of the project to stream the summary from.
   * @param reply - The Fastify reply object, used to send streaming responses.
   * @returns A stream of chat events, including tokens and the final summary message.
   * @throws ProjectNotFoundException if the project does not exist or is not owned by the user.
   * @throws ConversationEmptyException if there are no messages to summarise.
   * @throws LlmUnavailableException if the LLM service is unavailable.
   * @throws LlmResponseBlockedException if the LLM response is blocked due to content filtering.
   * @throws TooManyRequestsException if the user exceeds the rate limit for streaming requests.
   */
  @Post('summary/stream')
  @SkipEnvelope()
  async summaryStream(
    @CurrentUser() user: AuthUser,
    @Param('projectId') projectId: string,
    @Res() reply: FastifyReply,
  ) {
    const ac = this.abortOnDisconnect(reply);
    await this.pipe(
      reply,
      this.chat.streamSummary(user.id, projectId, ac.signal),
    );
  }

  private abortOnDisconnect(reply: FastifyReply) {
    const ac = new AbortController();
    reply.raw.on('close', () => {
      if (!reply.raw.writableEnded) ac.abort();
    });
    return ac;
  }

  private async pipe(reply: FastifyReply, events: AsyncGenerator<ChatEvent>) {
    // Pre-flight: any error here is still a normal JSON error via the global filter
    let step = await events.next();

    reply.hijack();
    reply.raw.writeHead(200, {
      'Content-Type': 'text/event-stream; charset=utf-8',
      'Cache-Control': 'no-cache, no-transform',
      Connection: 'keep-alive',
      'X-Accel-Buffering': 'no',
    });
    reply.raw.flushHeaders();

    const write = (event: string, data: unknown) =>
      reply.raw.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`);

    try {
      while (!step.done) {
        write(step.value.event, step.value.data);
        step = await events.next();
      }
    } catch (err) {
      const body =
        err instanceof AppException
          ? { message: err.message, code: err.code }
          : {
              message: 'Internal server error',
              code: ErrorCode.INTERNAL_ERROR,
            };
      this.logger.error(
        `Stream failed: ${body.code}`,
        err instanceof Error ? err.stack : undefined,
      );
      write('error', body);
    } finally {
      reply.raw.end();
    }
  }
}
